#!/usr/bin/env python3
"""
Merge Driver Results
This script takes a list of paths to JSON files generated by driver.py and merges them into
a single JSON file containing every driver run result entry found across all the provided JSONs.
It also shortens strings in *_stdout and *_stderr fields if they exceed a maximum length.
"""
import json
import argparse
import sys
from pathlib import Path


# Default maximum length for stdout/stderr strings before truncation
DEFAULT_MAX_STRING_LENGTH = 10000


def truncate_string(text: str, max_length: int) -> str:
    """Truncate a string by removing text from the middle if it exceeds max_length.

    Args:
        text: The string to truncate
        max_length: Maximum allowed length

    Returns:
        The truncated string with ellipses indicating removed content
    """
    if len(text) <= max_length:
        return text

    # Calculate how much to keep from each end
    # Reserve space for the ellipsis message
    ellipsis_msg = "\n[... content removed ...]\n"
    ellipsis_len = len(ellipsis_msg)

    # Calculate available space for actual content
    available_space = max_length - ellipsis_len

    if available_space < 0:
        # If max_length is too small, just return the ellipsis message
        return ellipsis_msg.strip()

    # Split available space roughly in half (slightly favor the beginning)
    first_half = available_space // 2
    second_half = available_space - first_half

    # Get the beginning and end portions
    beginning = text[:first_half]
    end = text[-second_half:] if second_half > 0 else ""

    # Combine with ellipsis
    return beginning + ellipsis_msg + end


def process_entry(entry: dict, max_length: int) -> dict:
    """Process a single entry to truncate stdout/stderr fields.

    Args:
        entry: A driver result entry dictionary
        max_length: Maximum allowed length for stdout/stderr strings

    Returns:
        The entry with truncated stdout/stderr fields
    """
    processed_entry = entry.copy()

    # Fields that may contain long strings
    stdout_stderr_fields = ["build_stdout", "build_stderr", "run_stdout", "run_stderr"]

    for field in stdout_stderr_fields:
        if field in processed_entry and processed_entry[field] is not None:
            processed_entry[field] = truncate_string(processed_entry[field], max_length)

    return processed_entry


def load_json_file(file_path: Path) -> list:
    """Load and parse a JSON file.

    Args:
        file_path: Path to the JSON file

    Returns:
        List of entries from the JSON file

    Raises:
        SystemExit: If the file cannot be read or parsed
    """
    try:
        with open(file_path, "r", encoding="utf-8") as f:
            data = json.load(f)

        if not isinstance(data, list):
            print(f"Warning: {file_path} does not contain a JSON array. Skipping.", file=sys.stderr)
            return []

        return data
    except FileNotFoundError:
        print(f"Error: File not found: {file_path}", file=sys.stderr)
        sys.exit(1)
    except json.JSONDecodeError as e:
        print(f"Error: Invalid JSON in {file_path}: {e}", file=sys.stderr)
        sys.exit(1)


def merge_driver_results(input_files: list[Path], output_file: Path, max_length: int) -> None:
    """Merge multiple driver result JSON files into a single file.

    Args:
        input_files: List of paths to input JSON files
        output_file: Path to the output JSON file
        max_length: Maximum allowed length for stdout/stderr strings
    """
    all_entries = []

    print(f"Processing {len(input_files)} input file(s)...")

    for file_path in input_files:
        print(f"  Loading {file_path}...")
        entries = load_json_file(file_path)
        print(f"    Found {len(entries)} entries")

        # Process each entry to truncate long strings
        processed_entries = [process_entry(entry, max_length) for entry in entries]
        all_entries.extend(processed_entries)

    print(f"\nTotal entries: {len(all_entries)}")

    # Write merged results to output file
    print(f"Writing merged results to {output_file}...")
    with open(output_file, "w", encoding="utf-8") as f:
        json.dump(all_entries, f, indent=4)
    print(f"Successfully wrote {len(all_entries)} entries to {output_file}")


def parse_args() -> argparse.Namespace:
    """Parse command line arguments."""
    parser = argparse.ArgumentParser(
        description="Merge multiple driver result JSON files into a single file, "
                    "truncating long stdout/stderr strings."
    )
    parser.add_argument(
        "input_files",
        nargs="+",
        type=Path,
        help="Paths to input JSON files generated by driver.py"
    )
    parser.add_argument(
        "-o", "--output",
        type=Path,
        default=Path("merged_driver_results.json"),
        help="Path to output JSON file (default: merged_driver_results.json)"
    )
    parser.add_argument(
        "--max-length",
        type=int,
        default=DEFAULT_MAX_STRING_LENGTH,
        help="Maximum length for stdout/stderr strings before truncation (default: " \
            + f"{DEFAULT_MAX_STRING_LENGTH})"
    )
    return parser.parse_args()


def main() -> None:
    """Main function."""
    args = parse_args()

    # Validate input files exist
    for file_path in args.input_files:
        if not file_path.exists():
            print(f"Error: Input file does not exist: {file_path}", file=sys.stderr)
            sys.exit(1)

    merge_driver_results(args.input_files, args.output, args.max_length)


if __name__ == "__main__":
    main()
